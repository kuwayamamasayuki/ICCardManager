namespace ICCardManager.Common
{
    /// <summary>
    /// 二重起動を中止したときの案内文言（Issue #1910）
    /// </summary>
    /// <remarks>
    /// <para>
    /// 起動済みの画面を前面へ出せた場合は<b>案内を表示しない</b>。
    /// 画面が前に出ること自体が「新しく起動しなかった」ことの可視の応答であり、
    /// 交通系ICカードをタッチする前に職員へ余分なクリックを強いない
    /// （<c>.claude/rules/error-messages.md</c> の 3 要素は、案内を出すときの品質基準であって
    /// 「常に案内を出せ」という要求ではない）。
    /// </para>
    /// <para>
    /// 前面へ出せなかったときだけ、<b>前面化の結果</b>（<see cref="ActivationOutcome"/>）に応じて
    /// 「どうすれば」を変えて表示する。ミューテックスの判定結果（<see cref="SingleInstanceStatus"/>）で
    /// 選んではならない — あれは DACL の所有者、つまり別ユーザーかどうかしか表さないため、
    /// <b>同じユーザーが 2 セッションで起動している場合</b>（コンソール＋リモートデスクトップ、
    /// ユーザーの簡易切り替え）に「タスクバーで切り替えてください」という
    /// このセッションでは実行できない指示になる（Issue #1757「取れる行動が違う経路には専用のファクトリ」）。
    /// </para>
    /// </remarks>
    public static class SingleInstanceNotice
    {
        /// <summary>案内ダイアログのタイトル</summary>
        public const string Title = "ピッすいは既に起動しています";

        /// <summary>すべての文言に共通する「何が」「なぜ」の部分</summary>
        private const string CommonCause =
            "ピッすいは既にこのパソコンで起動しているため、起動を中止しました。" +
            "二重に起動すると、1 回のタッチが 2 回読み取られ、貸出の直後に返却として記録されてしまいます。";

        /// <summary>
        /// 同じセッションに切り替え先の画面がある場合の案内
        /// （前面化が Windows のフォアグラウンドロックで拒否されたとき）
        /// </summary>
        public static string BuildSameSessionMessage()
            => CommonCause +
               "タスクバーの「ピッすい」を選んで、起動中のピッすいの画面に切り替えてください。";

        /// <summary>
        /// 同じパソコンの別のユーザーで起動していると確定した場合の案内
        /// （名前付きミューテックスへのアクセスが DACL で拒否された）
        /// </summary>
        public static string BuildOtherUserSessionMessage()
            => "ピッすいはこのパソコンの別のユーザーで起動しているため、起動を中止しました。" +
               "1 台のカードリーダーを 2 つのピッすいから同時に使うことはできません。" +
               "起動中のユーザーに切り替えるか、そのユーザーにピッすいの終了を依頼してください。";

        /// <summary>
        /// 起動していることは確かだが、切り替え先の画面がこのセッションに見つからない場合の案内
        /// </summary>
        /// <remarks>
        /// 同じユーザーの別セッション（リモートデスクトップ・ユーザーの簡易切り替え）と、
        /// 先行インスタンスがまだ画面を表示していない場合の<b>両方</b>があり得る。
        /// どちらかを断定すると片方で誤った案内になるため、両方で実行できる指示にする
        /// （<c>error-messages.md</c>「取れる行動が違う経路には専用のファクトリ」）。
        /// </remarks>
        public static string BuildWindowNotFoundMessage()
            => CommonCause +
               "起動中のピッすいの画面は、このパソコンのタスクバーには見つかりませんでした。" +
               "起動した直後で画面がまだ表示されていないか、別のユーザーやリモートデスクトップの接続で" +
               "起動している可能性があります。少し待ってからもう一度起動するか、" +
               "起動中のユーザーに切り替えてピッすいを終了してください。";
    }
}
